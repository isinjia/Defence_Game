// ===== 게이트 크로니클: 메인 막간 (docs/종합_평가_v1.91.md 3순위 G) =====
// 메인 장은 등급으로 열려서, 한 부를 몇 달 만에 마친 뒤 다음 등급까지 몇 년 동안 메인이 조용하다.
// 그 공백에 다음 부의 복선과 메인 인물 근황을 짧은 사건으로 보여 준다. 다음 장이 몇 급에서 열리는지도 넌지시 알린다.
// 조건: 다음 장이 아직 안 열렸고(등급 부족), 앞 장을 마친 지 a 개월 이상, 같은 공백의 앞 막간을 본 지 10개월 이상.

{
  const waitGap = (g, part) => {
    const M = g.flags && g.flags.main; if (!M) return -1;
    const def = MAIN.chapters[M.ch]; if (!def || def.part !== part || M.open[def.n] || M.done[def.n]) return -1;
    if (g.player.rankIdx >= (def.rank || 0)) return -1;
    const prev = M.done[def.n - 1]; if (!prev) return -1;
    return g.monthKey() - prev.mk;
  };
  const doneOk = (g, n) => { const M = g.flags.main; return !!(M && M.done[n] && M.done[n].how !== 'missed'); };
  const fill = (s) => (g) => g.mainFill(s);
  // 막간 정의: 파트, 순서(0 첫째·1 둘째), 최소 공백(개월), 추가 조건
  const I = (part, order, minGap, def) => S({
    id: `mi_${part}_${order}`, once: true, weight: 3,
    when: (g, c) => {
      const gap = waitGap(g, part); if (gap < minGap) return false;
      if (order > 0) { const prev = g.flags.seen[`mi_${part}_${order - 1}`]; if (prev == null || g.monthKey() - prev < 10) return false; }
      return !def.need || def.need(g);
    },
    text: fill(def.text), choices: def.choices.map((ch) => ({ text: ch.text, do: (g, c) => g.mainFill(ch.do(g, c)) })),
  });
  const friendRel = (g, d) => { const f = g.mainWho('friend'); if (f && f.id != null && g.changeRel) { g.changeRel(f, d, '메인 막간'); return ` (${f.name} 관계 +${d})`; } return ''; };
  const rk = (n) => RANKS[n].key;

  // ---- 1부 → 2부 (D급에서 열림) ----
  I(2, 0, 6, {
    text: '강북 폐구 쪽 전봇대에 새 전단이 붙었다. 이번엔 갈라진 원이 아니다. 둥글게 늘어선 점 다섯 개. 아래 한 줄: "다섯 번째 보름에, 모두 함께."',
    choices: [
      { text: '한 장 떼어 수첩에 끼운다', do: () => `점 다섯 개가 도시 지도 위 어딘가와 겹쳐 보인다. 아직은 무엇인지 모르겠다. 협회는 ${rk(2)}급부터 균열교 관련 조사를 맡긴다고 했다.` },
      { text: '협회 제보 창구에 사진을 올린다', do: (g) => '"접수되었습니다." 자동 답장 한 줄. 그 뒤로 아무 연락도 없다.' + g.gain({ merit: 1 }) },
    ] });
  I(2, 1, 12, {
    need: (g) => !!g.mainWho('friend'),
    text: '{friend}에게서 늦은 밤 문자가 온다. "요즘 목요일마다 무료 급식소 봉사 다녀. 거기 사람들, 생각보다 괜찮아. 너도 한번 와 볼래?"',
    choices: [
      { text: '"그 급식소, 누가 운영하는데?"', do: (g) => '한참 뒤 답이 온다. "몰라. 다들 그냥 \'선생님\'이라고 불러." 화면을 오래 본다.' + friendRel(g, 2) },
      { text: '"좋은 일 하네. 몸조심하고."', do: (g) => '"응ㅋㅋ 너야말로." 웃는 이모티콘 하나.' + friendRel(g, 3) },
    ] });

  // ---- 2부 → 3부 (C급에서 열림) ----
  I(3, 0, 6, {
    need: (g) => doneOk(g, 9),
    text: '모르는 주소의 메일 한 통. 제목 없음. 본문은 숫자 표 하나와 한 줄. "대구 분지 지열 측정치. 작년 대비 4도. 게이트 탓이라고 하기엔 너무 고르다. — 한"',
    choices: [
      { text: '표를 저장해 둔다', do: () => `숫자가 계절도 날씨도 타지 않고 한 방향으로만 오른다. ${rk(3)}급쯤 되면 관리국도 이런 일을 그냥 넘기지 못할 것이다.` },
      { text: '"왜 저한테 보내요?"라고 답장한다', do: () => '답이 온다. "당신은 지우라는 말을 안 들으니까요." 그 뒤로 그 주소는 존재하지 않는다고 뜬다.' },
    ] });
  I(3, 1, 14, {
    text: '꿈. 문이 하나 있다. 문 너머에서 누군가 숫자를 센다. 하나, 둘, 셋… 어디까지 셌는지 잊은 듯 다시 처음부터. 목소리는 지쳐 있지만 세는 걸 멈추지 않는다.',
    choices: [
      { text: '같이 세어 본다', do: (g) => '어느 숫자에서 목소리가 멈칫한다. 당신 목소리를 들은 것 같다. 깨어나니 손바닥이 차갑다.' + g.gain({ ether: 15 }) },
      { text: '문을 두드린다', do: () => '숫자 세는 소리가 뚝 끊긴다. 긴 침묵. 그리고 아주 작게, "아직." 잠에서 깬다.' },
    ] });

  // ---- 3부 → 4부 (B급에서 열림) ----
  I(4, 0, 6, {
    need: (g) => !!g.mainWho('rival'),
    text: '헌터넷 인기 글. "{rival}, 관리국 특채 거절하고 개인 파티 꾸림. 첫 공략이 강원 심층 게이트." 댓글 맨 위: "미쳤네. 근데 멋있다."',
    choices: [
      { text: '축하 메시지를 보낸다', do: () => `답이 늦게 온다. "넌 아직 거기냐. 빨리 올라와. ${rk(4)}급 판은 공기가 달라."` },
      { text: '글을 끝까지 읽기만 한다', do: () => '공략 영상 마지막 장면. {rival}이(가) 카메라를 보지 않고 바다 쪽을 보고 있다.' },
    ] });
  I(4, 1, 14, {
    text: '강릉 해안 전선에서 올라온 짧은 영상이 돈다. 새벽 바다 밑에서 초록빛이 맥박처럼 깜빡인다. 해안 경비대원이 중얼거린다. "저거, 숨 쉬는 거 아냐?" 영상은 하루 만에 내려갔다.',
    choices: [
      { text: '영상을 따로 저장해 둔다', do: () => '깜빡이는 간격을 세어 본다. 일정하다. 심장 박동처럼.' },
      { text: '해안 전선 근무 공고를 찾아본다', do: () => `"${rk(4)}급 이상 지원 가능." 아직은 지원 자격이 없다.` },
    ] });

  // ---- 4부 → 5부 (A급에서 열림) ----
  I(5, 0, 6, {
    text: '협회 공지: "북부 봉쇄선 인근 무단 접근 증가. 위반 시 자격 정지." 같은 날 헌터넷에는 봉쇄선 너머에서 찍었다는 사진 한 장. 멈춘 시계탑이 이십 년 전 그 시각을 가리킨다.',
    choices: [
      { text: '사진의 위치를 추적해 본다', do: () => `시계탑 그림자 각도로 보면 오전이다. 봉쇄선 출입 허가는 ${rk(5)}급부터 나온다.` },
      { text: '공지만 읽고 넘긴다', do: () => '봉쇄선. 대붕괴 뒤로 아무도 돌아오지 않은 땅. 그런데 누군가 사진을 찍어 왔다.' },
    ] });
  I(5, 1, 14, {
    need: (g) => !!g.mainWho('friend'),
    text: '{friend}와 오랜만에 포장마차. 소주잔을 돌리다 {friend}이(가) 묻는다. "넌 끝이 어딘지 알아? 등급 말고. 이 일의 끝."',
    choices: [
      { text: '"문 하나 닫는 거."', do: (g) => '{friend}이(가) 웃는다. "그 문, 꽤 크겠다." 잔을 부딪친다.' + friendRel(g, 4) },
      { text: '"모르겠어. 그래서 계속 가는 거야."', do: (g) => '"그럼 갈 때 나도 불러." 농담 같지 않은 목소리.' + friendRel(g, 4) },
    ] });

  // ---- 5부 → 6부 (S급에서 열림) ----
  I(6, 0, 6, {
    text: '속보. "제주 해협 봉쇄 함대 증강. 관리국, 섬 주변 비행 금지 구역 확대." 화면 속 섬 위로 구름이 둥글게 돌고 있다. 태풍도 아닌데.',
    choices: [
      { text: '제주 쪽 하늘을 오래 본다', do: () => `구름의 회전 방향이 꿈속 문틀의 무늬와 같다. 그 섬에 들어갈 수 있는 건 ${rk(6)}급뿐이다.` },
      { text: '채널을 돌린다', do: () => '다른 채널도 같은 화면이다.' },
    ] });
  I(6, 1, 14, {
    text: '꿈. 문 앞에 누군가 앉아 있다. 등만 보인다. "오래 걸리네." 원망하는 목소리가 아니다. "괜찮아. 기다리는 건 잘하니까."',
    choices: [
      { text: '"곧 갈게."', do: (g) => '등이 조금 펴진다. 깨어나니 창밖이 밝다.' + g.gain({ ether: 25 }) },
      { text: '아무 말 없이 옆에 앉는다', do: (g) => '둘이서 한참 문을 본다. 깨어나니 이상하게 개운하다.' + g.gain({ hp: 0.5 }) },
    ] });
}
