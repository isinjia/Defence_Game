    const bad = (arr) => !arr || arr.some((l) => (fam === 'plain' ? polite(l) : fam === 'hage' || fam === 'hao' ? true : !polite(l)));
    if (bad(P.orderOk)) P.orderOk = ORDER[fam].ok;
