  for (const [id, lines] of Object.entries(PERSONA_GREET)) if (PERSONAS[id]) Object.assign(PERSONAS[id], lines);

  const GP = Game.prototype;
  const GREET_KEYS = ['greet', 'leadGreet', 'leadBrief', 'welcome'];
  const baseLine = GP.personaLine;
  GP.personaLine = function (n, key, vars = {}, used) {
    if (!GREET_KEYS.includes(key)) return baseLine.call(this, n, key, vars, used);
    const P = this.personaOf(n); if (!P) return null;
    const cands = P[key] || [];
    let pool = used ? cands.filter((s) => !used.has(s)) : cands;
    if (!pool.length) pool = cands; // 다 썼으면 처음부터(같은 성격이 셋 이상일 때)
    if (!pool.length) return null;
    const s = RNG.pick(pool); if (used) used.add(s);
    const cls = vars.cls || (typeof classById === 'function' && n.cls ? classById(n.cls).name : '헌터');
    const listener = vars.name || (this.player ? this.player.name : '');
    // 이름 뒤 서술격 조사(예요/이에요, 야/이야, 라고/이라고, 다/이다 …)를 받침에 맞춘다
    const val = { me: n.name || '', cls, name: listener };
    const out = s.replace(/\{(me|cls|name)\}(예요|요|야|라고|라는|라니|라 |다|여|였|고요|죠|지)?/g, (m, k, j) => {
      const w = val[k]; if (!j) return w;
      const last = w.charCodeAt(w.length - 1); const has = last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 !== 0;
      if (!has) return w + j;
      return w + ({ '예요': '이에요', '요': '이요', '고요': '이고요', '죠': '이죠', '지': '이지', '야': '이야', '라고': '이라고', '라는': '이라는', '라니': '이라니', '라 ': '이라 ', '다': '이다', '여': '이여', '였': '이었' }[j]);
    });
    return typeof fixJosa === 'function' ? fixJosa(out) : out;
  };
  GP.personaGreetScene = function () { return new Set(); };
