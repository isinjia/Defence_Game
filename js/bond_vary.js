(() => {
  if (typeof PERS_BOND === 'undefined' || typeof S !== 'function' || typeof Game === 'undefined') return;
  // 원래 장면의 선택지·효과를 그대로 붙여 변형 장면을 등록
  for (const [pers, stages] of Object.entries(PERS_BOND_ALT)) {
    stages.forEach((alts, st) => {
      const base = typeof STORY !== 'undefined' && STORY.find((e) => e.id === `bond_${pers}_${st}`);
      if (!base) return;
      alts.forEach((text, k) => S({ ...base, id: `bond_${pers}_${st}_v${k + 1}`, text }));
    });
  }
  const GP = Game.prototype;
  const baseId = GP.bondSceneId;
  GP.bondSceneId = function (n) {
    const id = baseId.call(this, n);
    try {
      const f = this.flags; f.bondSeenTxt ??= {};
      const m = /^bond_([a-z]+)_(\d)$/.exec(id); if (!m) return id;
      const opts = [id, ...((PERS_BOND_ALT[m[1]] || [])[+m[2]] || []).map((_, k) => `${id}_v${k + 1}`)].filter((x) => this.storyById(x));
      const pick = opts.find((x) => !f.bondSeenTxt[x]) || opts[Math.floor(RNG.next() * opts.length)] || id;
      f.bondSeenTxt[pick] = this.monthKey();
      return pick;
    } catch (e) { return id; }
  };
})();
