// 성격 대사 하나 (없으면 null). k: 0 찬성 1 반대 2 막아서기 3 수용 4 거부
function personaCouncil(n, k) {
  if (!n || typeof G === 'undefined' || !G.personaOf) return null;
  G.personaOf(n); const L = PERSONA_COUNCIL[n.persona];
  return L && L[k] ? `"${L[k]}"` : null;
}

if (typeof Game !== 'undefined') {
  // 상황이 담긴 줄(샘·보물·쉬자)은 남기고, 일반 찬반 줄을 성격 말투로
  const KEEP = new Set([...(COUNCIL_LINES.restX || []), ...(COUNCIL_LINES.restO || []), ...(COUNCIL_LINES.treasureO || [])]);
  const base = Game.prototype.councilOpinion;
  Game.prototype.councilOpinion = function (n, t, hpR, leaderRel) {
    const r = base.call(this, n, t, hpR, leaderRel);
    if (!r || !r.line || KEEP.has(r.line) || Math.random() < 0.3) return r;
    const s = personaCouncil(n, r.vote === 'X' ? 1 : 0);
    return s ? { ...r, line: s } : r;
  };
}

if (typeof UI !== 'undefined') {
  const SAY = { '"…알았어. 네 판단 믿어 볼게."': 3, '"그래도 난 반대야."': 4 };
  // 설득 결과 줄
  const baseRender = UI.renderCouncil;
  UI.renderCouncil = function () {
    const cn = this.ctx && this.ctx.council;
    if (cn && cn.votes) for (const v of cn.votes) if (v.line && SAY[v.line] != null) v.line = personaCouncil(G.npcById(v.id), SAY[v.line]) || v.line;
    return baseRender.apply(this, arguments);
  };
  // 막아서기: 관계·통찰 줄은 그대로, 일반 줄만 성격 말투로
  const baseLine = UI.blockLine;
  UI.blockLine = function (b) {
    const s = baseLine.call(this, b);
    if (b.why === 'sign' || b.why === 'hopeless' || !b.n || b.n.relation >= 70 || b.n.relation <= -10) return s;
    return personaCouncil(b.n, 2) || s;
  };
  const baseShow = UI.showBlock;
  UI.showBlock = function (b) {
    if (b && b.line === '"말로는 안 돼. 비킬 수 없어."') b.line = personaCouncil(b.n, 4) || b.line;
    return baseShow.call(this, b);
  };
  // 토스트로 나오는 고정 대사를 성격 말투로 (막아서기 설득 성공, NPC 리더 결정)
  const swapToast = (fn, pick) => function (...a) {
    const t0 = this.toast; const self = this;
    this.toast = function (msg, ...r) { return t0.call(self, pick.call(self, msg) || msg, ...r); };
    try { return fn.apply(this, a); } finally { this.toast = t0; }
  };
  UI.blockResolve = swapToast(UI.blockResolve, function (msg) {
    const n = this.ctx && this.ctx.block && this.ctx.block.n; if (!n) return null;
    if (msg === `${n.name}: "…좋아. 네 판단을 믿어 볼게."`) { const s = personaCouncil(n, 3); return s && `${n.name}: ${s}`; }
    return null;
  });
  UI.councilNpcDecide = swapToast(UI.councilNpcDecide, function (msg) {
    const cn = this.ctx && this.ctx.council; const L = cn && G.npcById(cn.leader); if (!L) return null;
    if (msg === `${L.name}: "내가 책임진다. 간다."`) { const s = personaCouncil(L, 0); return s && `${L.name}: ${s} 그대로 밀고 나간다.`; }
    if (msg.startsWith(`${L.name}: "…그래, 네 말도 일리가 있어."`)) { const s = personaCouncil(L, 3); return s && msg.replace('"…그래, 네 말도 일리가 있어."', s); }
    return null;
  });
}
